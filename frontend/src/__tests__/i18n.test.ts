import { describe, it, expect, beforeEach } from 'vitest'
import { locale, setLocale, t, messages } from '../lib/i18n'

describe('lib/i18n', () => {
  beforeEach(() => {
    setLocale('zh')
  })

  it('zh and en dictionaries stay symmetric (same key set)', () => {
    const zhKeys = Object.keys(messages.zh).sort()
    const enKeys = Object.keys(messages.en).sort()
    expect(enKeys).toEqual(zhKeys)
  })

  it('t gets current locale dict value (zh)', () => {
    expect(t('nav.home')).toBe('本机')
    expect(t('settings.themeMode')).toBe('深色模式')
  })

  it('t returns key as-is when missing', () => {
    expect(t('no.such.key')).toBe('no.such.key')
  })

  it('apiRouteMode settings keys render in both locales and mention the tray return path', () => {
    setLocale('zh')
    expect(t('settings.apiRouteMode')).toBe('API 路由模式')
    expect(t('settings.apiRouteModeDesc')).toContain('显示主窗口')
    expect(t('settings.apiRouteModeDevBlocked')).toContain('wails dev')
    expect(t('settings.apiRouteModeRequiresTray')).toContain('系统托盘')
    expect(t('settings.apiRouteModeError')).not.toBe('settings.apiRouteModeError')
    setLocale('en')
    expect(t('settings.apiRouteMode')).toBe('API Route Mode')
    expect(t('settings.apiRouteModeDesc')).toContain('Show Main Window')
    expect(t('settings.apiRouteModeDevBlocked')).toContain('wails dev')
    expect(t('settings.apiRouteModeRequiresTray')).toContain('system tray')
    expect(t('settings.apiRouteModeError')).not.toBe('settings.apiRouteModeError')
  })

  it('about settings keys render in both locales', () => {
    setLocale('zh')
    expect(t('settings.about')).toBe('关于')
    expect(t('settings.version')).toBe('版本')
    expect(t('settings.license')).toBe('开源协议')
    expect(t('settings.repo')).toBe('项目仓库')
    setLocale('en')
    expect(t('settings.about')).toBe('About')
    expect(t('settings.version')).toBe('Version')
    expect(t('settings.license')).toBe('License')
    expect(t('settings.repo')).toBe('Repository')
  })

  it('non-Windows updates hint keys render in both locales and point at GitHub Releases', () => {
    setLocale('zh')
    expect(t('settings.updateNotSupported')).toBe('自动更新当前仅支持 Windows，请前往 GitHub Releases 获取新版本。')
    expect(t('settings.updateReleasesLink')).toBe('GitHub Releases')
    setLocale('en')
    expect(t('settings.updateNotSupported')).toContain('Windows-only')
    expect(t('settings.updateNotSupported')).toContain('GitHub Releases')
    expect(t('settings.updateReleasesLink')).toBe('GitHub Releases')
  })

  it('runtime section and shared download labels render in both locales', () => {
    setLocale('zh')
    expect(t('runtime.llamacpp.path')).toBe('安装路径')
    expect(t('runtime.downloadDir')).toBe('下载路径')
    expect(t('runtime.compMain')).toContain('llama-server')
    expect(t('runtime.compCudart')).toContain('CUDA')
    expect(t('runtime.pkgCudart')).toContain('CUDA')
    expect(t('dl.downloading')).toBe('正在下载')
    expect(t('dl.error')).toBe('下载失败')
    setLocale('en')
    expect(t('runtime.llamacpp.path')).toBe('Install Path')
    expect(t('runtime.downloadDir')).toBe('Download Path')
    expect(t('runtime.compMain')).toContain('llama-server')
    expect(t('runtime.compCudart')).toContain('CUDA')
    expect(t('runtime.pkgCudart')).toContain('CUDA')
    expect(t('dl.downloading')).toBe('Downloading')
    expect(t('dl.error')).toBe('Download failed')
  })

  it('android directory hint key renders in both locales', () => {
    setLocale('zh')
    expect(t('models.dirAndroidHint')).toBe('安卓版使用应用内存储，路径由系统管理')
    setLocale('en')
    expect(t('models.dirAndroidHint')).toBe('Android uses app-internal storage; paths are managed by the system')
  })

  it('chat vision-guidance keys render in both locales (issue #35)', () => {
    setLocale('zh')
    expect(t('chat.attachBlocked')).toContain('mmproj')
    expect(t('chat.imagesNeedVision')).toContain('mmproj')
    expect(t('chat.errorVision', { msg: 'boom' })).toContain('boom')
    expect(t('chat.errorVision', { msg: 'boom' })).toContain('mmproj')
    expect(t('downloads.mmprojHint')).toContain('mmproj')
    setLocale('en')
    expect(t('chat.attachBlocked')).toContain('mmproj')
    expect(t('chat.imagesNeedVision')).toContain('mmproj')
    expect(t('chat.errorVision', { msg: 'boom' })).toContain('boom')
    expect(t('chat.errorVision', { msg: 'boom' })).toContain('mmproj')
    expect(t('downloads.mmprojHint')).toContain('mmproj')
  })

  it('settings docs-entry keys render in both locales (former nav docs entry card)', () => {
    setLocale('zh')
    expect(t('settings.docsEntry')).toBe('帮助与教程')
    expect(t('settings.docsEntrySub')).toContain('教程')
    setLocale('en')
    expect(t('settings.docsEntry')).toBe('Help & Tutorial')
    expect(t('settings.docsEntrySub')).toContain('guide')
  })

  it('settings device-island keys render in both locales (frame ⑤ redesign)', () => {
    setLocale('zh')
    expect(t('settings.device')).toBe('设备')
    expect(t('settings.os.android')).toBe('Android')
    expect(t('settings.os.windows')).toBe('Windows')
    expect(t('settings.os.darwin')).toBe('macOS')
    expect(t('settings.os.other')).not.toBe('settings.os.other')
    expect(t('settings.groupAppearance')).toContain('外观')
    expect(t('settings.groupService')).toContain('目录')
    expect(t('settings.languageAutoShort')).toBe('自动')
    expect(t('settings.accessLocalShort')).toBe('本地')
    expect(t('settings.accessLanShort')).toBe('局域网')
    expect(t('settings.sourceHfShort')).toContain('HF')
    expect(t('settings.sourceMsShort')).toBe('魔搭')
    setLocale('en')
    expect(t('settings.device')).toBe('Device')
    expect(t('settings.os.android')).toBe('Android')
    expect(t('settings.os.windows')).toBe('Windows')
    expect(t('settings.os.darwin')).toBe('macOS')
    expect(t('settings.os.other')).not.toBe('settings.os.other')
    expect(t('settings.groupAppearance')).toContain('Appearance')
    expect(t('settings.groupService')).toContain('Directories')
    expect(t('settings.languageAutoShort')).toBe('Auto')
    expect(t('settings.accessLocalShort')).toBe('Local')
    expect(t('settings.accessLanShort')).toBe('LAN')
    expect(t('settings.sourceHfShort')).toBe('HF Mirror')
    expect(t('settings.sourceMsShort')).toBe('ModelScope')
  })

  it('t supports {name} placeholder interpolation', () => {
    expect(t('downloads.selectedCount', { n: 3 })).toBe('已选 3 个文件')
    expect(t('api.saveFailed', { msg: 'boom' })).toBe('配置保存失败: boom')
  })

  it('models tune keys render in both locales with interpolated tune results', () => {
    setLocale('zh')
    expect(t('models.tune')).not.toBe('models.tune')
    expect(t('models.tuneError', { msg: 'boom' })).toContain('boom')
    expect(t('models.tuneError', { msg: 'boom' })).not.toBe('models.tuneError')
    const zhTuned = t('models.tuned', { gpu: 'all', ctx: 32768, cache: 'f16', threads: 8 })
    expect(zhTuned).not.toBe('models.tuned')
    expect(zhTuned).toContain('32768')
    setLocale('en')
    expect(t('models.tune')).not.toBe('models.tune')
    expect(t('models.tuneError', { msg: 'boom' })).toContain('boom')
    expect(t('models.tuneError', { msg: 'boom' })).not.toBe('models.tuneError')
    const enTuned = t('models.tuned', { gpu: 'all', ctx: 32768, cache: 'f16', threads: 8 })
    expect(enTuned).not.toBe('models.tuned')
    expect(enTuned).toContain('32768')
  })

  it('home redesign greeting/hero/storage keys render in both locales', () => {
    setLocale('zh')
    expect(t('home.greet.morning')).toBe('早上好 👋')
    expect(t('home.greet.afternoon')).toBe('下午好 👋')
    expect(t('home.greet.evening')).toBe('晚上好 🌙')
    expect(t('home.greet.online', { model: 'Qwen3-4B' })).toBe('Qwen3-4B 在线')
    expect(t('home.greet.offline')).toContain('服务未运行')
    expect(t('home.hero.tagReady')).toBe('AI 就绪')
    expect(t('home.hero.tagOffline')).toBe('离线')
    expect(t('home.hero.cta')).toContain('进入对话')
    expect(t('home.hero.metricLbl')).toContain('tokens')
    expect(t('home.storage.modelsValue', { n: 4, size: '12.7 GB' })).toBe('4 个 · 12.7 GB')
    expect(t('home.storage.notInstalled')).toBe('未安装')
    expect(t('home.memory.aux', { pct: 43, free: '9.1 GB' })).toBe('43% · 可用 9.1 GB')
    expect(t('home.cpu.aux', { model: 'Snapdragon 8 Gen 3', n: 8 })).toContain('8 核')
    setLocale('en')
    expect(t('home.greet.morning')).toBe('Good morning 👋')
    expect(t('home.greet.evening')).toBe('Good evening 🌙')
    expect(t('home.greet.online', { model: 'Qwen3-4B' })).toBe('Qwen3-4B online')
    expect(t('home.greet.offline')).toBe('Service stopped')
    expect(t('home.hero.tagReady')).toBe('AI ready')
    expect(t('home.hero.tagOffline')).toBe('Offline')
    expect(t('home.hero.cta')).toContain('Chat now')
    expect(t('home.storage.modelsValue', { n: 4, size: '12.7 GB' })).toBe('4 models · 12.7 GB')
    expect(t('home.storage.notInstalled')).toBe('Not installed')
    expect(t('home.memory.aux', { pct: 43, free: '9.1 GB' })).toBe('43% · 9.1 GB free')
    expect(t('home.cpu.aux', { model: 'Snapdragon 8 Gen 3', n: 8 })).toContain('8 cores')
  })

  it('after setLocale, t returns corresponding language', () => {
    setLocale('en')
    expect(t('nav.home')).toBe('System')
    expect(t('settings.themeMode')).toBe('Dark Mode')
    // English interpolation
    expect(t('downloads.selectedCount', { n: 3 })).toBe('3 files selected')
  })

  it('locale defaults to zh, setLocale updates locale.value', () => {
    expect(locale.value).toBe('zh')
    setLocale('en')
    expect(locale.value).toBe('en')
    setLocale('zh')
    expect(locale.value).toBe('zh')
  })

  it('remote probe status keys render in both locales and carry the two empty-picker causes', () => {
    // Chat.vue remote tier: the unreachable warning (with a retry action)
    // vs the reachable-but-nothing-loaded hint explaining the lazy load
    setLocale('zh')
    expect(t('chat.remoteProbeFail')).toContain('无法连接远程电脑')
    expect(t('chat.remoteProbeFail')).toContain('防火墙')
    expect(t('chat.remoteProbeRetry')).toBe('重试')
    expect(t('chat.remoteEmptyHint')).toContain('没有已加载的模型')
    expect(t('chat.remoteEmptyHint')).toContain('懒加载')
    setLocale('en')
    expect(t('chat.remoteProbeFail')).toContain('Cannot reach the remote PC')
    expect(t('chat.remoteProbeFail')).toContain('firewall')
    expect(t('chat.remoteProbeRetry')).toBe('Retry')
    expect(t('chat.remoteEmptyHint')).toContain('no loaded models')
    expect(t('chat.remoteEmptyHint')).toContain('lazy-loads')
  })
})
