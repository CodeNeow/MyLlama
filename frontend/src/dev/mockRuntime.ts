// ─── fetch interception (chat page talks to llama-server directly) ──────────

const sleep = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms))

const json = (body: unknown, status = 200): Response =>
  new Response(JSON.stringify(body), {
    status,
    headers: { 'Content-Type': 'application/json' },
  })

/** OpenAI-compatible SSE stream with a visibly paced typing effect.
 * Honors the request's AbortSignal: the chat page's stop button aborts the
 * fetch, so the stream must stop enqueueing and error the controller (mirrors
 * a real fetch, whose body reader rejects with the abort reason).
 * With the ?sc=chatthink scenario active, a reasoning prelude streams first
 * as `reasoning_content` deltas (design frame ⑥ collapsible think block). */
function chatCompletionResponse(signal?: AbortSignal | null): Response {
  const encoder = new TextEncoder()
  const reply = mockChatReply()
  // 2-character slices ≈ one CJK token per chunk, 30ms apart.
  const pieces: string[] = []
  for (let i = 0; i < reply.length; i += 2) pieces.push(reply.slice(i, i + 2))
  const think = mockChatThinkParts()
  const reasoningPieces: string[] = []
  if (think) {
    for (let i = 0; i < think.reasoning.length; i += 2) reasoningPieces.push(think.reasoning.slice(i, i + 2))
  }
  // chatthink scenario: a visibly slower pace so the transient streaming
  // states (expanded think block / typing dots / red stop) stay observable
  // during the walkthrough capture.
  const pace = think ? 150 : 30
  const body = new ReadableStream<Uint8Array>({
    async start(controller) {
      // Abort mid-stream: surface the abort reason to the body reader so the
      // chat page's catch sees the same AbortError a real server would cause.
      const onAbort = () => {
        try {
          controller.error(signal?.reason ?? new DOMException('The user aborted a request.', 'AbortError'))
        } catch {
          // Stream already closed or errored (abort raced the completion) — nothing to abort.
        }
      }
      if (signal?.aborted) {
        onAbort()
        return
      }
      signal?.addEventListener('abort', onAbort, { once: true })
      try {
        for (const piece of reasoningPieces) {
          await sleep(pace)
          if (signal?.aborted) return // listener already errored the controller
          try {
            controller.enqueue(
              encoder.encode('data: ' + JSON.stringify({ choices: [{ delta: { reasoning_content: piece } }] }) + '\n\n'),
            )
          } catch {
            // Abort raced the enqueue (flag read just before the listener fired):
            // the controller is already errored, so stop feeding it silently.
            return
          }
        }
        for (const piece of pieces) {
          await sleep(pace)
          if (signal?.aborted) return // listener already errored the controller
          try {
            controller.enqueue(
              encoder.encode('data: ' + JSON.stringify({ choices: [{ delta: { content: piece } }] }) + '\n\n'),
            )
          } catch {
            // Abort raced the enqueue (flag read just before the listener fired):
            // the controller is already errored, so stop feeding it silently.
            return
          }
        }
        try {
          controller.enqueue(encoder.encode('data: [DONE]\n\n'))
          controller.close()
        } catch {
          // Same abort race on the closing chunk: the reader already got the
          // abort reason, closing a dead controller is a no-op.
        }
      } finally {
        signal?.removeEventListener('abort', onAbort)
      }
    },
  })
  return new Response(body, { status: 200, headers: { 'Content-Type': 'text/event-stream' } })
}

/** Router/OpenAI model list shared with the GetLoadedModels mock state. */
function modelsResponse(directModeFallback: boolean): Response {
  const data = mockLoadedModels().map((m) =>
    directModeFallback
      ? { id: m.id, object: 'model' }
      : { id: m.id, object: 'model', status: { value: m.status } },
  )
  return json({ object: 'list', data })
}

async function handleMockServerRequest(url: URL, init: RequestInit | undefined): Promise<Response> {
  const path = url.pathname
  const method = (init?.method ?? 'GET').toUpperCase()
  // Direct-mode fallback shape (src/lib/chat.ts): every served model is loaded.
  if (method === 'GET' && path === '/models') {
    return mockServerRunning() ? modelsResponse(false) : json({ error: { message: 'llama-server is not running (mock)' } }, 503)
  }
  if (method === 'GET' && path === '/v1/models') {
    return mockServerRunning() ? modelsResponse(true) : json({ error: { message: 'llama-server is not running (mock)' } }, 503)
  }
  if (method === 'POST' && path === '/v1/chat/completions') {
    if (!mockServerRunning()) {
      return json({ error: { message: 'llama-server is not running (mock)' } }, 503)
    }
    mockAddServerLog('srv  update_slots: all slots are busy')
    return chatCompletionResponse(init?.signal)
  }
  if (method === 'POST' && path === '/models/unload') {
    mockAddServerLog('[INFO] router: model unload request accepted (mock)')
    return json({ ok: true })
  }
  return json({ error: { message: 'mock llama-server has no route for ' + method + ' ' + path } }, 404)
}

// Install once per page: requests aimed at the mock llama-server
// (127.0.0.1:<mockServerPort()>) are answered locally, everything else goes to
// the real network untouched.
const fetchMarker = '__llamaMockFetchInstalled' as const
if (!(globalThis as any)[fetchMarker]) {
  ;(globalThis as any)[fetchMarker] = true
  const originalFetch = globalThis.fetch.bind(globalThis)
  globalThis.fetch = async (input: RequestInfo | URL, init?: RequestInit): Promise<Response> => {
    let url: URL | null = null
    try {
      url = new URL(typeof input === 'string' ? input : input instanceof URL ? input.href : input.url)
    } catch {
      url = null
    }
    if (url && url.hostname === '127.0.0.1' && url.port === String(mockServerPort())) {
      return handleMockServerRequest(url, init)
    }
    return originalFetch(input, init)
  }
}
